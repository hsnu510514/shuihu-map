// 由 data/portraits/manifest.json 產生 src/data/portraits.ts（請勿手改產生檔）。
// 用法：node scripts/build-portraits.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = resolve(root, 'data/portraits/manifest.json')
const outPath = resolve(root, 'src/data/portraits.ts')

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))

function commonsUrl(title) {
  return `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(title.replace(/ /g, '_'))}`
}

const figures = {}
for (const [figureId, sources] of Object.entries(manifest.figures)) {
  figures[figureId] = sources.map((source) => ({
    id: `${figureId}-${source.id}`,
    label: source.label,
    artist: source.artist,
    era: source.era,
    license: source.license,
    credit: source.credit ?? (source.license === 'ref' ? '版權歸原權利人' : 'Wikimedia Commons'),
    sourceUrl: source.sourceUrl ?? (source.commons ? commonsUrl(source.commons) : undefined),
    file: source.file ?? `portraits/${figureId}-${source.id}.jpg`,
  }))
}

const header = `// AUTO-GENERATED by scripts/build-portraits.mjs — do not edit by hand.
// 由 data/portraits/manifest.json 產生；執行 npm run build:portraits 更新。
export type PortraitLicense = 'pd' | 'cc' | 'ref'

export interface PortraitSource {
  id: string
  label: string
  artist?: string
  era?: string
  license: PortraitLicense
  credit?: string
  sourceUrl?: string
  file: string
}

export const portraitsByFigure: Record<string, PortraitSource[]> = `

const body = JSON.stringify(figures, null, 2)

const footer = `

export function portraitsFor(figureId: string): PortraitSource[] {
  return portraitsByFigure[figureId] ?? []
}
`

writeFileSync(outPath, header + body + '\n' + footer, 'utf8')
console.log(`已產生 ${outPath}（${Object.keys(figures).length} 位人物）`)
