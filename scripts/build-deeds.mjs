import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const IN_DIR = path.join(ROOT, 'data', 'deeds')
const OUT = path.join(ROOT, 'src', 'data', 'deeds.ts')

const TYPES = {
  captures: 'DeedCapture',
  fights: 'DeedFight',
  kills: 'DeedKill',
  campaigns: 'DeedCampaign',
}

function readJsonl(file) {
  if (!fs.existsSync(file)) return []
  return fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line, index) => {
      try {
        return JSON.parse(line)
      } catch (error) {
        throw new Error(`${path.basename(file)} line ${index + 1}: ${error.message}`)
      }
    })
}

const blocks = []
const present = []
const usedTypes = []

for (const [name, typeName] of Object.entries(TYPES)) {
  const records = readJsonl(path.join(IN_DIR, `${name}.jsonl`))
  if (records.length === 0) continue
  present.push(name)
  usedTypes.push(typeName)
  const body = records.map((record) => `  ${JSON.stringify(record)},`).join('\n')
  blocks.push(`export const ${name}: ${typeName}[] = [\n${body}\n]`)
}

const header = [
  '// AUTO-GENERATED by scripts/build-deeds.mjs — do not edit by hand.',
  usedTypes.length ? `import type { ${usedTypes.join(', ')} } from './types'` : '',
  '',
  '',
].join('\n')

fs.writeFileSync(OUT, `${header}${blocks.join('\n\n')}\n`, 'utf8')
console.log(`wrote ${path.relative(ROOT, OUT)} (${present.join(', ') || 'empty'})`)
